let language = "zh-CN";
export function normalizeLanguage(value) {
  if (typeof value !== "string") return null;
  const tag = value.toLowerCase();
  if (tag === "zh" || tag.startsWith("zh-")) return "zh-CN";
  if (tag === "en" || tag.startsWith("en-")) return "en";
  return null;
}
export function chooseLanguage({ query, stored, browser } = {}) {
  return normalizeLanguage(query) || normalizeLanguage(stored) ||
    normalizeLanguage(browser) || "en";
}
export function setLanguage(value) {
  language = normalizeLanguage(value) || language;
  return language;
}
export function getLanguage() { return language; }
export function t(source, values = {}, locale = language) {
  const template = locale === "en" ? (EN[source] ?? source) : source;
  return template.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}
export function runtimeMessage(message) {
  const text = String(message || "");
  const asset = /^资源加载失败 \((\d+)\): (.+)$/.exec(text);
  return asset ? t("资源加载失败 ({status})：{path}", { status: asset[1], path: asset[2] }) : t(text);
}
// Capture only the authored UI at startup, never player-generated names or game data.
// Translating text nodes preserves SVG icons, form values, event handlers and focus.
export function bindStaticTranslations(root) {
  const bindings = [];
  const doc = root.ownerDocument;
  const walker = doc.createTreeWalker(root, 4);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement?.closest("script,style,[data-language]")) continue;
    const source = node.nodeValue.replace(/\s+/g, " ").trim();
    if (Object.hasOwn(EN, source)) bindings.push(() => {
      if (node.isConnected) node.nodeValue = node.nodeValue.replace(node.nodeValue.trim(), t(source));
    });
  }
  for (const element of root.querySelectorAll("*"))
    for (const attr of ["aria-label", "title", "placeholder"]) {
      const source = element.getAttribute(attr);
      if (source && Object.hasOwn(EN, source))
        bindings.push(() => element.setAttribute(attr, t(source)));
    }
  return () => bindings.forEach(render => render());
}
