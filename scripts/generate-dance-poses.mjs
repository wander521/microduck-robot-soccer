// Generate original planted-foot squat keyframes with native MuJoCo forward kinematics.
import { writeFile } from "node:fs/promises";
import { loadPhysicsRuntime, PhysicsWorld } from "../src/physics/world.mjs";
import { createRoom, addPlayer, FIELD } from "../src/simulation.js";
import { DEFAULT_POSE } from "../src/physics/constants.js";
const room = createRoom();
room.ai = false;
const p = addPlayer(room, "sample", "Duck");
const world = new PhysicsWorld(await loadPhysicsRuntime(), room, FIELD);
const { model, data, runtime } = world,
  slot = world.slots.get(p.id);
const forward = () => runtime.mj.mj_forward(model, data);
forward();
function foot(geom) {
  const m = data.geom_xmat,
    o = geom * 9;
  return [
    data.geom_xpos[geom * 3],
    data.geom_xpos[geom * 3 + 2],
    Math.atan2(m[o + 2], m[o + 8]),
  ];
}
const targets = slot.feet.map(foot);
function solve(matrix, values) {
  const a = matrix.map((row, i) => [...row, values[i]]);
  for (let c = 0; c < 3; c++) {
    let pivot = c;
    for (let i = c + 1; i < 3; i++)
      if (Math.abs(a[i][c]) > Math.abs(a[pivot][c])) pivot = i;
    [a[c], a[pivot]] = [a[pivot], a[c]];
    const d = a[c][c];
    if (Math.abs(d) < 1e-10) return [0, 0, 0];
    for (let j = c; j < 4; j++) a[c][j] /= d;
    for (let i = 0; i < 3; i++)
      if (i !== c) {
        const f = a[i][c];
        for (let j = c; j < 4; j++) a[i][j] -= f * a[c][j];
      }
  }
  return a.map((row) => row[3]);
}
const frames = [];
let worst = 0;
for (let n = 0; n <= 80; n++) {
  const height = 0.125 - (n / 80) * 0.04;
  data.qpos[slot.baseQ + 2] = height;
  for (let side = 0; side < 2; side++) {
    const indices = side ? [11, 12, 13] : [2, 3, 4];
    for (let it = 0; it < 25; it++) {
      forward();
      const value = foot(slot.feet[side]);
      const error = targets[side].map((v, j) => v - value[j]);
      if (Math.hypot(...error) < 1e-7) break;
      const jac = [[], [], []];
      for (let c = 0; c < 3; c++) {
        const address = slot.qpos[indices[c]],
          before = data.qpos[address];
        data.qpos[address] = before + 0.00001;
        forward();
        const changed = foot(slot.feet[side]);
        data.qpos[address] = before;
        for (let r = 0; r < 3; r++)
          jac[r][c] = (changed[r] - value[r]) / 0.00001;
      }
      const delta = solve(jac, error);
      for (let c = 0; c < 3; c++)
        data.qpos[slot.qpos[indices[c]]] += Math.max(
          -0.15,
          Math.min(0.15, delta[c]),
        );
    }
  }
  forward();
  const errors = slot.feet.map((geom, i) =>
    Math.hypot(...foot(geom).map((v, j) => v - targets[i][j])),
  );
  worst = Math.max(worst, ...errors);
  const joints = slot.qpos.map((a) => data.qpos[a]);
  if (joints.some((v) => !Number.isFinite(v) || Math.abs(v) > 1.58))
    throw Error("Squat exceeds joint range");
  frames.push({ height, joints });
}
if (worst > 0.0001) throw Error(`IK residual too large ${worst}`);
await writeFile(
  new URL("../src/dance-squat.js", import.meta.url),
  "// Original planted-foot squat keyframes; generated by scripts/generate-dance-poses.mjs.\nexport const SQUAT_FRAMES = " +
    JSON.stringify(
      frames.map((f) => ({
        height: f.height,
        joints: f.joints.map((v) => Math.round(v * 1e6) / 1e6),
      })),
    ) +
    ";\n",
);
console.log(
  JSON.stringify({
    frames: frames.length,
    squatMillimetres: 40,
    worstResidual: worst,
  }),
);
world.dispose();
