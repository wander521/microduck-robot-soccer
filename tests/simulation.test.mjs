import test from "node:test";
import assert from "node:assert/strict";
import {
  createRoom,
  addPlayer,
  syncBots,
  tick,
  resetPlayer,
  resetPlay,
  snapshot,
  FIELD,
  BALL_COUNT,
} from "../src/simulation.js";
import { loadPhysicsRuntime, PhysicsWorld } from "../src/physics/world.mjs";
import { velocityCommand, projectedGravity } from "../src/physics/constants.js";
const runtime = await loadPhysicsRuntime();
function roomWithPlayer() {
  const room = createRoom();
  room.ai = false;
  const player = addPlayer(room, "a", "Player");
  room.physics = new PhysicsWorld(runtime, room, FIELD);
  return { room, player, world: room.physics };
}
async function steps(room, n) {
  for (let i = 0; i < n; i++) await tick(room);
}
test("Space resets the duck and moving, spinning ball even during inference", async () => {
  const { room, player, world } = roomWithPlayer();
  try {
    room.scores.blue = 2;
    world.setBall({
      x: 0.6,
      z: 0.3,
      y: 0.2,
      vx: 0.7,
      vz: 0.4,
      angular: [2, 3, 4],
    });
    const control = world.control.bind(world);
    world.control = async (...args) => {
      await control(...args);
      resetPlay(room, player);
    };
    await tick(room);
    world.control = control;
    const ball = world.readBall();
    assert.equal(room.balls.length, 1);
    assert.ok(Math.abs(ball.x) < 1e-8 && Math.abs(ball.z) < 1e-8);
    assert.ok(Math.abs(ball.vx) < 1e-8 && Math.abs(ball.vz) < 1e-8);
    assert.ok(ball.angular.every((v) => Math.abs(v) < 1e-8));
    assert.deepEqual(ball.quat, [1, 0, 0, 0]);
    assert.ok(Math.abs(player.x + 0.2) < 0.01);
    assert.deepEqual(room.scores, { blue: 2, orange: 0 });
    resetPlay(room, player);
    resetPlay(room, player);
    await tick(room);
    assert.equal(room.balls.length, 1);
    assert.ok(Math.abs(room.balls[0].x) < 1e-8);
  } finally {
    world.dispose();
  }
});
test("the pitch has exactly one shared ball at kickoff and after a goal", async () => {
  const { room, world } = roomWithPlayer();
  try {
    assert.equal(BALL_COUNT, 1);
    assert.equal(room.balls.length, 1);
    assert.equal(room.balls[0].x, 0);
    world.setBall({ x: FIELD.halfLength + 0.02, z: 0, y: 0.05 });
    await steps(room, 1);
    assert.deepEqual(room.scores, { blue: 1, orange: 0 });
    assert.equal(room.balls.length, 1);
    assert.equal(snapshot(room).balls.length, 1);
    assert.equal(room.balls[0].x, 0);
    await steps(room, 100);
    assert.equal(room.scores.blue, 1);
  } finally {
    world.dispose();
  }
});
