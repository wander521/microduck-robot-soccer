test("a trained kick changes the leg and transfers momentum through ball contact", async () => {
  const { room, player, world } = roomWithPlayer();
  try {
    await steps(room, 50);
    const pose = [...player.joints];
    world.setBall({ x: player.x + 0.13, z: player.z - 0.035, y: 0.05 });
    player.kickRequested = true;
    let peak = 0,
      poseChange = 0;
    for (let i = 0; i < 50; i++) {
      await tick(room);
      peak = Math.max(peak, Math.hypot(room.balls[0].vx, room.balls[0].vz));
      poseChange = Math.max(
        poseChange,
        ...player.joints.map((a, j) => Math.abs(a - pose[j])),
      );
    }
    assert.ok(peak > 0.1);
    assert.ok(poseChange > 0.1);
    assert.ok(player.height > 0.07);
    assert.equal(room.balls.length, 1);
  } finally {
    world.dispose();
  }
});

test("a fallen robot gets back up using the trained recovery policy", async () => {
  const { room, player, world } = roomWithPlayer();
  try {
    await steps(room, 50);
    const slot = world.slots.get(player.id);
    world.data.qpos.set(
      [player.x, -player.z, 0.17, Math.SQRT1_2, 0, Math.SQRT1_2, 0],
      slot.baseQ,
    );
    world.data.qvel.fill(0);
    world.runtime.mj.mj_forward(world.model, world.data);
    let entered = false,
      recovered = false;
    for (let i = 0; i < 200; i++) {
      await tick(room);
      if (player.recovery) entered = true;
      if (entered && !player.recovery && player.height > 0.08) {
        recovered = true;
        break;
      }
    }
    assert.ok(entered);
    assert.ok(recovered);
  } finally {
    world.dispose();
  }
});

