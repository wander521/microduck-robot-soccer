test("joining a player preserves existing physical state and AI yields its slots", async () => {
  const { room, player, world } = roomWithPlayer();
  try {
    player.forward = 1;
    await steps(room, 100);
    player.forward = 0;
    const before = player.x;
    addPlayer(room, "b", "B");
    await steps(room, 1);
    assert.ok(Math.abs(player.x - before) < 0.02);
    assert.equal(world.model.nu, 28);
    room.ai = true;
    syncBots(room);
    await steps(room, 1);
    assert.equal(room.players.size, 4);
    assert.equal([...room.players.values()].filter((p) => p.bot).length, 2);
    assert.equal(world.model.nu, 56);
    room.ai = false;
    syncBots(room);
    await steps(room, 1);
    assert.equal(room.players.size, 2);
  } finally {
    world.dispose();
  }
});
